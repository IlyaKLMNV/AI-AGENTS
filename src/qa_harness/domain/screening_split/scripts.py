_ALL_SCRIPTS: dict[str, str] = {**TERMINAL_SCRIPTS, **CONTINUE_SCRIPTS}

# Ключи, которые Аналитик имеет право вернуть (внутренний *_EMPTY сюда не входит).
KNOWN_KEYS: frozenset[str] = frozenset(
    set(TERMINAL_SCRIPTS) | (set(CONTINUE_SCRIPTS) - {"REPLY_CONTACT_SOURCE_EMPTY"})
)


def is_known(script_key: str) -> bool:
    """Допустимый ли это ключ из тех, что может вернуть Аналитик."""
    return script_key in KNOWN_KEYS


def is_terminal(script_key: str) -> bool:
    """Завершает ли скрипт диалог. Терминально всё, кроме REPLY_*."""
    return not script_key.startswith("REPLY_")


def render_script(script_key: str, *, city: str = "", contact_source: str = "") -> str | None:
    """Готовый текст по ключу с подстановками, либо None для неизвестного ключа
    (тогда оркестратор уходит в REPLY_FALLBACK)."""
    if script_key == "REPLY_CONTACT_SOURCE" and not (contact_source or "").strip():
        script_key = "REPLY_CONTACT_SOURCE_EMPTY"

    template = _ALL_SCRIPTS.get(script_key)
    if template is None:
        return None
    return template.format(city=city, contact_source=contact_source)
