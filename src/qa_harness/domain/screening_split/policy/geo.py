"""Город кандидата против локации вакансии. Два предиката, нужных и сборке вопроса, и таблице правил.

Отдельный модуль, потому что читают его `core` (о чём спрашивать) и `rules` (когда отсеивать), а
`core` уже импортирует `rules` — общее место обязано лежать ниже обоих.

Радиусов здесь нет и не будет: расстояний у кода нет, а справочник агломераций («Химки — это Москва»)
— это отдельный источник данных, которого в контуре не существует. В промпте v2 радиусы прикидывала
МОДЕЛЬ («Москва — сам город + до 100 км, прочие — + до 50 км»), то есть отсев зависел от её
географических познаний. Здесь вопрос ставится иначе: не «далеко ли кандидат», а «готов ли он
работать из нужного города» — на это отвечает сам кандидат, и ответ проверяем.
"""


def same_city(candidate_city: str, location: str) -> bool:
    """Совпадает ли город кандидата с локацией вакансии — по нормализованной строке.

    Подстрочное совпадение: локацию вакансии пишут шире города («Россия, Москва», «Москва, Пресня»).
    """
    def norm(value: str) -> str:
        value = (value or "").strip().lower().replace("ё", "е")
        for prefix in ("г. ", "г.", "город "):
            if value.startswith(prefix):
                value = value[len(prefix):]
        return " ".join(value.split())

    a, b = norm(candidate_city), norm(location)
    return bool(a) and bool(b) and (a == b or a in b or b in a)


def relocation_pointless(state: dict, ctx) -> bool:
    """Спрашивать про переезд бессмысленно: локации у вакансии нет либо кандидат уже в ней.

    Город неизвестен → `False`: спросить надо, и это же оставляет отсев по формату закрытым до
    ответа. Догадка «раз города не назвал, наверное не здесь» стоила бы ложного отказа.
    """
    if not getattr(ctx, "location", ""):
        return True
    city = state.get("candidate_city")
    return bool(city) and same_city(city, ctx.location)
