_ALL_SCRIPTS: dict[str, str] = {**TERMINAL_SCRIPTS, **CONTINUE_SCRIPTS}

# Ключи, которые Аналитик имеет право вернуть.
KNOWN_KEYS: frozenset[str] = frozenset(set(TERMINAL_SCRIPTS) | set(CONTINUE_SCRIPTS))


def is_known(script_key: str) -> bool:
    """Допустимый ли это ключ из тех, что может вернуть Аналитик (hh-реестр)."""
    return script_key in KNOWN_KEYS


def is_terminal(script_key: str) -> bool:
    """Завершает ли скрипт диалог. Терминально всё, кроме REPLY_*."""
    return not script_key.startswith("REPLY_")


def render_script(script_key: str, *, city: str = "") -> str | None:
    """Готовый текст по ключу с подстановкой `{city}`, либо None для неизвестного ключа
    (тогда оркестратор уходит в REPLY_FALLBACK). Пустая «Локация» не ломает текст —
    подстановка безопасна (EGGPLANT_SPLIT_TASK.md подводный камень 9)."""
    template = _ALL_SCRIPTS.get(script_key)
    if template is None:
        return None
    return template.format(city=city)
